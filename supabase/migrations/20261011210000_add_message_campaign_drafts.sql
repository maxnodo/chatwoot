CREATE TABLE IF NOT EXISTS public.nodo_message_campaign_drafts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  inbox_id bigint NOT NULL REFERENCES public.inboxes(id) ON DELETE CASCADE,
  conversation_id bigint NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  recurring_message_id bigint REFERENCES public.nodo_weekly_recurring_messages(id) ON DELETE SET NULL,
  objective text NOT NULL CHECK (char_length(objective) BETWEEN 1 AND 1000),
  content text NOT NULL CHECK (char_length(content) BETWEEN 1 AND 4000),
  status text NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review', 'approved', 'rejected', 'scheduled')),
  proposed_for timestamptz NOT NULL,
  approved_by_user_id bigint,
  approved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_nodo_campaign_drafts_review
  ON public.nodo_message_campaign_drafts (account_id, conversation_id, status, proposed_for);

ALTER TABLE public.nodo_message_campaign_drafts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.nodo_message_campaign_drafts FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.nodo_message_campaign_drafts TO service_role;
