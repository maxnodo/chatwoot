CREATE TABLE IF NOT EXISTS public.nodo_weekly_recurring_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  inbox_id bigint NOT NULL REFERENCES public.inboxes(id) ON DELETE CASCADE,
  conversation_id bigint NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  conversation_display_id bigint NOT NULL,
  content text NOT NULL CHECK (char_length(content) BETWEEN 1 AND 4000),
  weekday smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  local_time time without time zone NOT NULL,
  timezone text NOT NULL DEFAULT 'Europe/Madrid',
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'cancelled')),
  next_run_at timestamptz NOT NULL,
  last_materialized_at timestamptz,
  created_by_user_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_nodo_weekly_recurring_due
  ON public.nodo_weekly_recurring_messages (next_run_at)
  WHERE status = 'active';

CREATE INDEX IF NOT EXISTS idx_nodo_weekly_recurring_conversation
  ON public.nodo_weekly_recurring_messages (account_id, conversation_display_id, status);

CREATE UNIQUE INDEX IF NOT EXISTS idx_nodo_scheduled_messages_recurring_occurrence
  ON public.nodo_scheduled_messages ((metadata ->> 'recurring_id'), send_at)
  WHERE metadata ? 'recurring_id';

