CREATE OR REPLACE FUNCTION public.nodo_next_coc_news_run(
  p_frequency text,
  p_weekday smallint,
  p_local_time time without time zone,
  p_after timestamptz DEFAULT now()
) RETURNS timestamptz
LANGUAGE plpgsql
STABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  local_date date;
  days_ahead integer;
  candidate timestamptz;
BEGIN
  IF p_frequency NOT IN ('daily', 'weekly') THEN RAISE EXCEPTION 'invalid frequency'; END IF;
  IF p_frequency = 'weekly' AND p_weekday NOT BETWEEN 0 AND 6 THEN RAISE EXCEPTION 'weekday is required'; END IF;
  local_date := (p_after AT TIME ZONE 'Europe/Madrid')::date;
  days_ahead := CASE
    WHEN p_frequency = 'daily' THEN 0
    ELSE (p_weekday - EXTRACT(DOW FROM local_date)::integer + 7) % 7
  END;
  candidate := ((local_date + days_ahead) + p_local_time) AT TIME ZONE 'Europe/Madrid';
  IF candidate <= p_after + interval '30 seconds' THEN
    candidate := ((local_date + days_ahead + CASE WHEN p_frequency = 'daily' THEN 1 ELSE 7 END) + p_local_time)
      AT TIME ZONE 'Europe/Madrid';
  END IF;
  RETURN candidate;
END;
$$;

CREATE OR REPLACE FUNCTION public.nodo_claim_due_coc_news_runs()
RETURNS TABLE (run_id uuid, schedule_id bigint, account_id bigint, assistant_id bigint, inbox_id bigint,
  conversation_id bigint, conversation_display_id bigint, topic text, lookback_days text, scheduled_for timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  schedule_row public.nodo_coc_recurring_news_schedules%ROWTYPE;
  new_run public.nodo_coc_recurring_news_runs%ROWTYPE;
BEGIN
  FOR schedule_row IN
    SELECT * FROM public.nodo_coc_recurring_news_schedules
    WHERE status = 'active' AND next_run_at <= now()
    ORDER BY next_run_at
    FOR UPDATE SKIP LOCKED
  LOOP
    INSERT INTO public.nodo_coc_recurring_news_runs (schedule_id, scheduled_for, status)
    VALUES (schedule_row.id, schedule_row.next_run_at, 'preparing')
    ON CONFLICT (schedule_id, scheduled_for) DO NOTHING
    RETURNING * INTO new_run;

    UPDATE public.nodo_coc_recurring_news_schedules
    SET next_run_at = public.nodo_next_coc_news_run(frequency, weekday, local_time, schedule_row.next_run_at + interval '1 second'),
        updated_at = now()
    WHERE id = schedule_row.id;

    IF new_run.id IS NOT NULL THEN
      INSERT INTO public.nodo_coc_recurring_news_events (schedule_id, run_id, event_type, payload)
      VALUES (schedule_row.id, new_run.id, 'prepared', jsonb_build_object('scheduled_for', new_run.scheduled_for));
      run_id := new_run.id;
      schedule_id := schedule_row.id;
      account_id := schedule_row.account_id;
      assistant_id := schedule_row.assistant_id;
      inbox_id := schedule_row.inbox_id;
      conversation_id := schedule_row.conversation_id;
      conversation_display_id := schedule_row.conversation_display_id;
      topic := schedule_row.topic;
      lookback_days := schedule_row.lookback_days;
      scheduled_for := new_run.scheduled_for;
      RETURN NEXT;
    END IF;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.nodo_claim_coc_news_deliveries()
RETURNS TABLE (run_id uuid, schedule_id bigint, account_id bigint, inbox_id bigint,
  conversation_id bigint, conversation_display_id bigint, content text, attempt integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  run_row public.nodo_coc_recurring_news_runs%ROWTYPE;
BEGIN
  FOR run_row IN
    SELECT * FROM public.nodo_coc_recurring_news_runs
    WHERE status = 'delivery_pending' AND next_attempt_at <= now() AND delivery_attempts < 3
    ORDER BY next_attempt_at, created_at
    FOR UPDATE SKIP LOCKED
  LOOP
    UPDATE public.nodo_coc_recurring_news_runs
    SET status = 'delivering', delivery_attempts = run_row.delivery_attempts + 1, updated_at = now()
    WHERE id = run_row.id;
    SELECT s.id, s.account_id, s.inbox_id, s.conversation_id, s.conversation_display_id
      INTO schedule_id, account_id, inbox_id, conversation_id, conversation_display_id
    FROM public.nodo_coc_recurring_news_schedules s WHERE s.id = run_row.schedule_id;
    run_id := run_row.id;
    content := run_row.message_content;
    attempt := run_row.delivery_attempts + 1;
    RETURN NEXT;
  END LOOP;
END;
$$;

