CREATE TABLE public.nodo_coc_recurring_news_schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  assistant_id bigint NOT NULL REFERENCES public.captain_assistants(id) ON DELETE RESTRICT,
  inbox_id bigint NOT NULL REFERENCES public.inboxes(id) ON DELETE RESTRICT,
  conversation_id bigint NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  conversation_display_id bigint NOT NULL,
  contact_id bigint NOT NULL REFERENCES public.contacts(id) ON DELETE RESTRICT,
  contact_inbox_id bigint NOT NULL REFERENCES public.contact_inboxes(id) ON DELETE RESTRICT,
  frequency text NOT NULL CHECK (frequency IN ('daily', 'weekly')),
  weekday smallint CHECK (weekday BETWEEN 0 AND 6),
  local_time time without time zone NOT NULL,
  timezone text NOT NULL DEFAULT 'Europe/Madrid' CHECK (timezone = 'Europe/Madrid'),
  topic text NOT NULL CHECK (char_length(trim(topic)) BETWEEN 1 AND 500),
  lookback_days text NOT NULL DEFAULT '1' CHECK (lookback_days IN ('1', '7', '30')),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'cancelled')),
  next_run_at timestamptz NOT NULL,
  created_by_user_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((frequency = 'daily' AND weekday IS NULL) OR (frequency = 'weekly' AND weekday IS NOT NULL))
);

CREATE UNIQUE INDEX nodo_coc_recurring_news_active_fingerprint
  ON public.nodo_coc_recurring_news_schedules
    (conversation_id, frequency, COALESCE(weekday, -1), local_time, topic, lookback_days)
  WHERE status = 'active';

CREATE INDEX nodo_coc_recurring_news_due
  ON public.nodo_coc_recurring_news_schedules (next_run_at)
  WHERE status = 'active';

CREATE INDEX nodo_coc_recurring_news_contact
  ON public.nodo_coc_recurring_news_schedules (account_id, conversation_id, status);
CREATE INDEX nodo_coc_recurring_news_assistant
  ON public.nodo_coc_recurring_news_schedules (assistant_id);
CREATE INDEX nodo_coc_recurring_news_inbox
  ON public.nodo_coc_recurring_news_schedules (inbox_id);
CREATE INDEX nodo_coc_recurring_news_contact_id
  ON public.nodo_coc_recurring_news_schedules (contact_id);
CREATE INDEX nodo_coc_recurring_news_contact_inbox
  ON public.nodo_coc_recurring_news_schedules (contact_inbox_id);

CREATE TABLE public.nodo_coc_recurring_news_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  schedule_id bigint NOT NULL REFERENCES public.nodo_coc_recurring_news_schedules(id) ON DELETE CASCADE,
  scheduled_for timestamptz NOT NULL,
  status text NOT NULL CHECK (status IN ('preparing', 'awaiting_analysis', 'delivery_pending', 'delivering', 'delivered', 'failed', 'cancelled')),
  analysis_id uuid,
  prepared_at timestamptz,
  coverage_from timestamptz,
  coverage_until timestamptz,
  message_content text,
  preparation_attempts integer NOT NULL DEFAULT 0 CHECK (preparation_attempts BETWEEN 0 AND 3),
  delivery_attempts integer NOT NULL DEFAULT 0 CHECK (delivery_attempts BETWEEN 0 AND 3),
  next_attempt_at timestamptz,
  delivery_message_id bigint,
  delivered_at timestamptz,
  error_code text,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (schedule_id, scheduled_for)
);

CREATE INDEX nodo_coc_recurring_news_runs_analysis
  ON public.nodo_coc_recurring_news_runs (status, updated_at)
  WHERE status IN ('preparing', 'awaiting_analysis');

CREATE INDEX nodo_coc_recurring_news_runs_delivery
  ON public.nodo_coc_recurring_news_runs (next_attempt_at, created_at)
  WHERE status = 'delivery_pending';

CREATE TABLE public.nodo_coc_recurring_news_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES public.nodo_coc_recurring_news_schedules(id) ON DELETE CASCADE,
  run_id uuid REFERENCES public.nodo_coc_recurring_news_runs(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN ('created', 'updated', 'paused', 'reactivated', 'cancelled', 'prepared', 'delivery_attempted', 'delivered', 'failed')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
